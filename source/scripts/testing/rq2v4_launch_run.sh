#!/usr/bin/env bash
# RQ2 v4 run launcher (runs on the cloud VM at ~/efficient-storage-in-edge-scenarios).
# usage: bash rq2v4_launch_run.sh <mode> <label> <seed> [extra_env_file ...]
#   mode ∈ {both, comp, stor, none} — scaling-mode capability ablation.
#   extra_env_file: optional additional controller env deltas merged AFTER the
#   mode delta (e.g. rq2v4_transport_*.env for the P1.4 RQ1-mode smoke set).
#
# Merge contract: build_network_setup.sh / run_experiment.sh accept exactly ONE
# OSKEN_ENV_OVERRIDE_FILE, so canonical + deltas are merged into one temp file
# (later files win on duplicate keys, one line per key) — precedent:
# research_q3_launch_run.sh. The run folder captures controller_env_snapshot.env
# with provenance comments.
#
# sudo has env_reset: launch knobs must be make command-line variables (they
# survive sudo; exported env vars do not). TELEMETRY_SOURCE / POLL_INTERVAL_S
# are read back by build_network_setup.sh from the recipe environment and
# forwarded as docker -e; DELAY_S / SAMPLE_EVERY / EVENT_POLL_INTERVAL_S are
# read by the controller from the merged env file.
set -u
cd ~/efficient-storage-in-edge-scenarios || exit 1
if [ "$#" -lt 3 ]; then
    echo "usage: bash rq2v4_launch_run.sh <mode> <label> <seed> [extra_env_file ...]"
    exit 1
fi
MODE="$1"
LABEL="$2"
SEED="$3"
shift 3
EXTRA_ENVS=("$@")

CANONICAL_ENV="source/scripts/testing/controller_env_overrides/current_state_integrated.env"
MODE_ENV="source/scripts/testing/controller_env_overrides/rq2v4_mode_${MODE}.env"
if [ ! -f "$MODE_ENV" ]; then
    echo "[rq2v4] unknown mode '${MODE}' (expected: $MODE_ENV)"; exit 1
fi
for env in ${EXTRA_ENVS[@]+"${EXTRA_ENVS[@]}"}; do
    if [ ! -f "$env" ]; then
        echo "[rq2v4] extra env file not found: $env"; exit 1
    fi
done

MERGED_ENV="$(mktemp /tmp/rq2v4_merged_XXXXXX.env)"
# HASH_WORK_FACTOR (RQ2 v4 press constant): when set in the caller env it is
# carried to BOTH container families — make var → static edges (network
# scripts), merged controller env → controller → dynamic spawns
# (compute_node_manager). Unset everywhere ⇒ edge image default (single
# source of truth: edge_server_config.HASH_WORK_FACTOR_DEFAULT).
HASH_ENV=""
if [ -n "${HASH_WORK_FACTOR:-}" ]; then
    HASH_ENV="$(mktemp /tmp/rq2v4_hashwf_XXXXXX.env)"
    printf 'HASH_WORK_FACTOR=%s\n' "$HASH_WORK_FACTOR" > "$HASH_ENV"
fi
python3 - "$MERGED_ENV" "$CANONICAL_ENV" "$MODE_ENV" ${EXTRA_ENVS[@]+"${EXTRA_ENVS[@]}"} ${HASH_ENV:+"$HASH_ENV"} <<'PYEOF'
import sys

out_path = sys.argv[1]
sources = sys.argv[2:]
keys = []
values = {}
for path in sources:
    with open(path) as f:
        for line in f:
            line = line.rstrip("\r\n")
            s = line.strip()
            if not s or s.startswith("#") or "=" not in s:
                continue
            key = s.split("=", 1)[0].strip()
            if key not in values:
                keys.append(key)
            values[key] = s
with open(out_path, "w") as f:
    f.write("# RQ2 v4 merged controller override (generated by rq2v4_launch_run.sh)\n")
    for path in sources:
        f.write(f"#   source: {path}\n")
    f.write("#   later sources override earlier ones on duplicate keys.\n")
    for key in keys:
        f.write(values[key] + "\n")
PYEOF

# Knobs that build_network_setup.sh forwards with its own defaults must be
# lifted out of the merged file, or the -e default overrides the env file
# (POLL_INTERVAL_S) / the arm silently loses its transport knob.
MERGED_POLL="$(sed -n 's/^POLL_INTERVAL_S=//p' "$MERGED_ENV" | tail -n 1)"
MERGED_TELEMETRY="$(sed -n 's/^TELEMETRY_SOURCE=//p' "$MERGED_ENV" | tail -n 1)"
MERGED_HASH="$(sed -n 's/^HASH_WORK_FACTOR=//p' "$MERGED_ENV" | tail -n 1)"
if [ -n "$MERGED_POLL" ] && [ -z "${POLL_INTERVAL_S:-}" ]; then POLL_INTERVAL_S="$MERGED_POLL"; fi
if [ -n "$MERGED_TELEMETRY" ] && [ -z "${TELEMETRY_SOURCE:-}" ]; then TELEMETRY_SOURCE="$MERGED_TELEMETRY"; fi
# Lift the press constant too: whatever the merged env carries (caller export
# or canonical) becomes the single make-var value, so static and dynamic
# edges can never disagree.
if [ -n "$MERGED_HASH" ] && [ -z "${HASH_WORK_FACTOR:-}" ]; then HASH_WORK_FACTOR="$MERGED_HASH"; fi
if [ -n "$HASH_ENV" ]; then rm -f "$HASH_ENV"; fi

ulimit -n 65535
exec sudo -n make -C source/scripts setup_network create_clients setup_test_data run_experiment \
  OSKEN_ENV_OVERRIDE_FILE="$MERGED_ENV" \
  RUN_LABEL="$LABEL" \
  CLIENTS=${CLIENTS:-24} CONTENT_ITEMS=3000 USERS=100 DATA_SEED=42 \
  TRAFFIC_DRIVER_MODE=open_loop CURL_MAX_TIME=300 INFLIGHT_WINDOW=1024 DRAIN_S=30 \
  STORAGE_CPUS=${STORAGE_CPUS:-0.15} EDGE_CPUS=${EDGE_CPUS:-0.15} WAN_RTT_MS=185 RANDOM_SEED="$SEED" \
  EDGE_MONGO_READ_PREFERENCE=secondaryPreferred EDGE_MONGO_MAX_POOL_SIZE=6 \
  VIP_DATA_PER_CONNECTION_FLOWS=1 EDGE_FLOW_ISOLATION=1 \
  OVERLOAD_MIN_REQUESTS=${OVERLOAD_MIN_REQUESTS:-60} \
  ${TELEMETRY_SOURCE:+TELEMETRY_SOURCE=${TELEMETRY_SOURCE}} \
  ${POLL_INTERVAL_S:+POLL_INTERVAL_S=${POLL_INTERVAL_S}} \
  ${HASH_WORK_FACTOR:+HASH_WORK_FACTOR=${HASH_WORK_FACTOR}} \
  SKIP_CLIENTS=1 SKIP_SEED=1 SKIP_SNAPSHOT=1
